package com.example.schoolkanjigame.kanji

private data class PdfKanjiSeed(
    val grade: Int,
    val target: String,
    val reading: String,
    val sentence: String,
)

val pdfKanjiQuestions: List<KanjiQuestion> = buildPdfKanjiQuestions()

private fun buildPdfKanjiQuestions(): List<KanjiQuestion> =
    pdfKanjiSeeds.mapIndexed { index, seed ->
        val distractors = pdfKanjiSeeds
            .asSequence()
            .filter { it.grade == seed.grade && it.reading != seed.reading }
            .map { it.reading }
            .distinct()
            .take(3)
            .toList()
        KanjiQuestion(
            id = "pdf_${seed.grade}_${index}_${seed.target}",
            grade = seed.grade,
            fullSentence = seed.sentence,
            targetText = seed.target,
            readingAnswers = listOf(seed.reading) + distractors,
            writingAnswer = seed.target,
        )
    }

